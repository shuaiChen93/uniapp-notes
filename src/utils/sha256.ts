import sha256 from 'crypto-js/sha256'

/**
 * SHA-256 摘要（基于 crypto-js）
 * ══════════════════════════════════════════════════════════════════════
 * ── 为什么用 crypto-js，而不是浏览器自带的 Web Crypto ──────────────────
 * 小程序端**没有 crypto.subtle**。它是浏览器安全上下文（HTTPS + 安全来源）
 * 才有的 API，微信基础库只在 wx 上提供了 getRandomValues（取随机数），
 * 没有任何摘要能力。
 *
 * 写 crypto.subtle.digest 的后果不是「降级」，而是**真机上直接抛错**：
 * 用户设不了密码、也校验不了密码，而这个错误在 H5 调试时完全看不到。
 *
 * crypto-js 是纯 JS 实现，H5 / App / 小程序三端行为完全一致。
 * 它已于 4.2.0 停止维护，这对本项目的影响可以接受：我们只用到其中的
 * SHA-256 摘要——一个写死的、不会再变的算法实现，不存在需要跟进的安全更新。
 *
 * ── 为什么只导入 crypto-js/sha256 而不是整个 crypto-js ────────────────
 * 整包（AES / PBKDF2 / 各种编码器）压缩前超过 200KB，而小程序主包上限是 2MB。
 * 按子模块导入只拉进 core + sha256，能压到 30KB 以内。
 *
 * ── 关于编码 ──────────────────────────────────────────────────────────
 * 字符串入参由 crypto-js 内部按 UTF-8 编码（中文、emoji 的代理对都已处理），
 * 与 `crypto.createHash('sha256').update(str, 'utf8')` 的结果一致。
 * 这一点不是「相信库的实现」，而是由 tests/unit/sha256.spec.ts
 * 与 node:crypto 逐条交叉验证——中文与 emoji 一旦编码不一致，
 * 换库或升级时会静默地让所有已存密码校验失败，用户数据就再也打不开了。
 * ══════════════════════════════════════════════════════════════════════
 */

/**
 * 计算字符串的 SHA-256，返回 64 位小写十六进制。
 *
 * toString() 的默认编码器就是 Hex，输出为小写。
 * 校验密码时是拿两个哈希做**字符串相等**比较，大小写与长度必须稳定，
 * 因此这里不做任何额外的转换，也不加前缀。
 */
export function sha256Hex(message: string): string {
  return sha256(message).toString()
}
