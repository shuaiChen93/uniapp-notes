/**
 * 生成一个本地唯一 ID。
 *
 * 为什么不用 crypto.randomUUID()：小程序端没有 Web Crypto 的这个方法
 * （它是浏览器安全上下文才有的 API），真机上会直接报错。
 *
 * 为什么不用自增数字：本项目的记事只增不减，自增序号一旦因为删除
 * 或导入出现空洞，就会和「已删除的 ID」发生复用——用户会看到
 * 一条本以为已经删掉的记事又冒出来。随机后缀从根本上避免这个问题。
 *
 * 「时间戳(36 进制) + 随机数」在单机场景下足够唯一，
 * 且生成的串短、可读、便于日志排查。
 *
 * @param prefix 业务前缀，便于在日志里一眼看出这是什么 ID
 */
export function uuid(prefix = ''): string {
  const time = Date.now().toString(36)
  const random = Math.random().toString(36).slice(2, 10)
  return `${prefix}${time}${random}`
}
