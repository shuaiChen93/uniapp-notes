/**
 * 密码锁领域类型
 * ══════════════════════════════════════════════════════════════════════
 * 与其它类型模块的区别：本模块描述的数据**大部分不进入 Pinia**。
 *
 * 密码的盐与哈希由 utils/lock.ts 直接读写 storage（见 constants/storage.ts），
 * 因为验证过程不该经过会被响应式追踪、会在开发者工具里被序列化展示的状态层。
 * 这里定义类型，只是为了让那套直接读写的代码也有编译期约束。
 * ══════════════════════════════════════════════════════════════════════
 */

/**
 * 本地保存的密码凭据（只读形态）。
 *
 * ⚠️ 这个类型里**没有明文密码字段**，而且不应该被扩展出一个。
 * 校验方式永远是「把用户输入重新哈希一次，再与 hash 比对」，
 * 而不是「解密出原密码来比一比」——单向哈希不可逆，
 * 这正是即使数据被完整导出也无法还原出 PIN 的原因。
 */
export interface LockCredential {
  /** 随机盐，Base64 编码。每次设置密码时重新生成 */
  salt: string
  /** SHA-256(salt + pin) 的哈希值，小写十六进制 */
  hash: string
}

/**
 * 锁页的工作模式。
 *
 * 四种模式共用一套数字键盘与圆点指示器，只有文案与提交后的动作不同：
 *   setup   —— 首次设置密码，输入第一遍
 *   confirm —— 二次确认，必须与第一遍完全一致
 *   verify  —— 解锁校验，通过后进应用
 *   change  —— 修改密码的第一步：校验**当前**密码，通过后转 setup 重设
 *
 * change 与 verify 的差别只在「通过之后去哪」：
 *   verify → reLaunch 首页（他是从外面被拦进来的）；
 *   change → 转入 setup（他已经解锁了，是来换密码的）。
 * 因此两者共用同一段校验代码，只在通过之后分叉。
 *
 * 用状态机式的单一字段而不是多个布尔量（isSetup / isConfirm…），
 * 是因为页面的渲染分支必须严格互斥：漏判一个分支就会出现
 * 「设置密码时顶部显示的是『请输入密码解锁』」这类文案错位。
 * 单一枚举天然互斥，不需要额外维护约束。
 */
export type LockMode = 'setup' | 'confirm' | 'verify' | 'change'
