/**
 * 应用设置类型
 * ══════════════════════════════════════════════════════════════════════
 * 本模块的所有数据都是「设备本地偏好」，**不上传任何服务器**——
 * 本项目从设计上就没有后端（见 manifest.json 的说明）。
 *
 * 因此设置没有对应的 api 层：读写直接走 store + 持久化插件。
 * 默认值定义在 store/modules/settings.ts 里，本目录只放类型。
 * ══════════════════════════════════════════════════════════════════════
 */

/**
 * 主题模式。
 *
 * 默认浅色：这是一本「私密记事本」，长时间阅读文字的场景占绝大多数，
 * 浅色底在自然光下的可读性更好（暗色留作夜间可选项）。
 *
 * 只提供两个确定值，**不做「跟随系统」**：小程序端跟随系统主题需要
 * 额外监听 uni.onThemeChange，而它只在部分基础库版本可用；更麻烦的是
 * 语义冲突——用户手动选了浅色之后，系统一到晚上就把它改回深色，
 * 这种「我明明选过了它自己变」的困惑，比少一个选项严重得多。
 */
export type ThemeMode = 'light' | 'dark'

/**
 * 用户资料。
 *
 * ⚠️ 全部是可选的本地数据，与登录/账号体系无关：
 * 小程序个人主体不申请手机号、不获取 OpenID，用户从打开到使用
 * 全程不需要授权任何账号信息。昵称与头像只用来在设置页打个招呼，
 * 不填也完全不影响任何功能。
 */
export interface UserProfile {
  /** 昵称。空串表示未填写 */
  nickname: string
  /**
   * 头像的**本地文件路径**。
   *
   * chooseAvatar 返回的是临时路径（wxfile:// 开头），小程序重启后可能失效，
   * 因此设置头像时会用 uni.saveFile 转存为永久路径再存进来，
   * 详见 pages/settings/settings.vue。空串表示未设置。
   */
  avatar: string
}

export interface AppSettings {
  /** 主题模式 */
  theme: ThemeMode
  /**
   * 密码锁是否启用。
   *
   * 这个值的含义就是「本地是否存有密码凭据」，两者必须同步：
   * 开启 = 引导设置密码并写入 salts/hash；关闭 = 清除凭据。
   * 不存在「开着锁但没有密码」或「有密码但锁是关的」这两种中间态，
   * 否则启动拦截逻辑就得去猜用户到底想不想要锁。
   */
  lockEnabled: boolean
  /** 本地昵称与头像 */
  profile: UserProfile
}
