/**
 * 应用设置类型
 * ══════════════════════════════════════════════════════════════════════
 * 设置项全部是「本地偏好」，不上传服务端——
 * 震动、音效这类开关是设备相关的（同一个账号在平板和手机上
 * 可能想要不同的设置），存到服务端反而会出现「换台设备被同步成别人的习惯」。
 *
 * 因此本模块**没有对应的 mock 接口**：设置的读写直接走 store + 持久化插件，
 * 绕过了请求层。这是有意为之——为纯本地数据造一个假接口，
 * 只会让「哪些数据真的需要后端」这件事变得模糊。
 * 默认值定义在 store/modules/settings.ts 里。
 * ══════════════════════════════════════════════════════════════════════
 */

/**
 * 主题模式。
 *
 * 只提供两个确定值，**不做「跟随系统」**：
 * 小程序端跟随系统主题需要额外监听 `uni.onThemeChange`，
 * 而它只在部分基础库版本与平台上可用（H5 端至今没有对齐的实现）。
 * 更麻烦的是语义冲突——用户手动选了暗色之后，系统一到晚上就把它改回浅色，
 * 这种「我明明选过了它自己变」的困惑，比少一个选项严重得多。
 * 宁可让用户手动切，也不要给一个行为不确定的开关。
 */
export type ThemeMode = 'dark' | 'light'

export interface AppSettings {
  /** 射击时是否震动反馈 */
  vibration: boolean
  /** 是否播放音效 */
  sound: boolean
  /** 主题模式 */
  theme: ThemeMode
  /**
   * 是否在训练结束后自动保存成绩。
   *
   * 默认开启。提供关闭选项是为了满足「只想练手不想留记录」的场景——
   * 有些用户会连续试几十次找手感，全存下来会把历史列表刷屏。
   */
  autoSave: boolean
}
