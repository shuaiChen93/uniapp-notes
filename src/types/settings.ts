/**
 * 应用设置类型
 * ══════════════════════════════════════════════════════════════════════
 * 本模块的所有数据都是「设备本地偏好」，**不上传任何服务器**——
 * 本项目从设计上就没有后端（见 manifest.json 的说明）。
 *
 * 因此设置没有对应的 api 层：读写直接走 store + 持久化插件。
 * 默认值定义在 store/modules/settings.ts 里，本目录只放类型。
 * ══════════════════════════════════════════════════════════════════════
 */

/**
 * 主题模式。
 *
 * 默认浅色：这是一本「私密记事本」，长时间阅读文字的场景占绝大多数，
 * 浅色底在自然光下的可读性更好（暗色留作夜间可选项）。
 *
 * 只提供两个确定值，**不做「跟随系统」**：小程序端跟随系统主题需要
 * 额外监听 uni.onThemeChange，而它只在部分基础库版本可用；更麻烦的是
 * 语义冲突——用户手动选了浅色之后，系统一到晚上就把它改回深色，
 * 这种「我明明选过了它自己变」的困惑，比少一个选项严重得多。
 */
export type ThemeMode = 'light' | 'dark'

/**
 * 用户资料。
 *
 * ⚠️ 全部是可选的本地数据，与登录/账号体系无关：
 * 小程序个人主体不申请手机号、不获取 OpenID，用户从打开到使用
 * 全程不需要授权任何账号信息。昵称与头像只用来在设置页打个招呼，
 * 不填也完全不影响任何功能。
 */
export interface UserProfile {
  /** 昵称。空串表示未填写 */
  nickname: string
  /**
   * 头像的**本地文件路径**。
   *
   * 存进来之前必须用 uni.saveFile 转存成永久路径：chooseAvatar 给出的是
   * 临时路径（wxfile:// 开头），小程序重启后就失效了。
   *
   * ⚠️ 昵称与头像尚未实现——本版设置页只做密码锁开关、主题与隐私说明，
   * 字段先留在这里，等真正做的时候不必再改一次存储结构。
   * 空串表示未设置。
   */
  avatar: string
}

export interface AppSettings {
  /** 主题模式 */
  theme: ThemeMode
  /**
   * 密码锁是否启用。**默认为 true**——本应用的前提是「私密」，
   * 第一次打开就应该要求设置密码，而不是等用户去设置页里找开关。
   *
   * 这个值的含义就是「本地是否存有密码凭据」，两者必须同步：
   * 开启 = 引导设置密码并写入 salt/hash；关闭 = 清除凭据。
   * 不存在「开着锁但没有密码」或「有密码但锁是关的」这两种中间态，
   * 否则启动拦截逻辑就得去猜用户到底想不想要锁。
   */
  lockEnabled: boolean
  /**
   * 用户是否对「密码锁」做过明确选择。
   *
   * ⚠️ 这个字段存在的唯一目的是**数据迁移**，不要删：
   * lockEnabled 在早期版本里默认 false，而那批数据产生时还没有任何
   * 设置密码的入口，因此它表达的是「从未选择过」，而不是「主动关掉了锁」。
   * 两者在存储里完全同形，只能靠这个字段区分——没有它，老设备升级后
   * lockEnabled 会一直停在 false，用户看到的现象只是「密码功能好像没做」，
   * 而这类「什么都不报错、就是没反应」的问题最难排查。
   *
   * 任何一次「设置页拨动开关」或「锁页完成密码设置」都会把它置为 true，
   * 此后再启动就不会被迁移逻辑改回来。
   */
  lockConfigured: boolean
  /** 本地昵称与头像 */
  profile: UserProfile
}
