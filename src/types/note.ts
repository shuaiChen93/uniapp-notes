/**
 * 记事（Note）领域类型
 * ══════════════════════════════════════════════════════════════════════
 * 本文件只描述「数据结构长什么样」，不含任何默认值与常量
 * （那是 src/constants/ 的职责，见 types/index.ts 的说明）。
 * ══════════════════════════════════════════════════════════════════════
 */

/**
 * 一条记事。
 *
 * ── 为什么 date 是字符串而不是时间戳 ──────────────────────────────────
 * date 表达的是「这条记事属于哪一天」这个**日历概念**，而不是一个时刻。
 * 用时间戳存会立刻带来两个麻烦：
 *   ① 凌晨写的日记到底算今天还是昨天？按时间戳分组要引入时区与零点判定，
 *      按 'YYYY-MM-DD' 分组则是字符串相等，没有歧义；
 *   ② 用户手动把日期改成上周三，时间戳形式的「某天 00:00:00」还要处理
 *      时分秒污染，否则分组时会被算进另一天。
 *
 * createdAt / updatedAt 是**时刻**，因此保持时间戳——它们只用于排序与展示。
 */
export interface Note {
  /** 本地生成的唯一 ID，见 utils/id.ts 的 uuid() */
  id: string
  /** 标题。允许为空串（用户可能只想记一句话），展示时兜底为「无标题」 */
  title: string
  /** 正文，纯文本 */
  content: string
  /** 所属日期，格式固定为 'YYYY-MM-DD'（已按 `年-月-日` 补零） */
  date: string
  /** 创建时刻（毫秒时间戳） */
  createdAt: number
  /** 最后修改时刻（毫秒时间戳） */
  updatedAt: number
}

/**
 * 编辑页的表单模型：只包含**用户能改的字段**。
 *
 * 与 Note 分开而不是用 Partial<Note>：
 * Partial 会把 id、createdAt 这些「由系统维护」的字段也标成可选，
 * 于是保存逻辑里就不得不写一堆「这个字段到底该不该信表单」的判断。
 * 拆成两个类型后，边界在编译期就是清楚的——
 * 表单只能填这三个字段，其余字段一律由 store 生成。
 */
export interface NoteDraft {
  /** 有值 = 编辑已有记事；不传 = 新建 */
  id?: string
  title: string
  content: string
  /** 所属日期，'YYYY-MM-DD' */
  date: string
}

/**
 * 时间线上的一个日期分组。
 *
 * 首页把扁平的 Note[] 折叠成「一天一组」再渲染，
 * 折叠结果在 store 里以计算属性缓存（见 store/modules/notes.ts），
 * 避免每次输入框变化都重算整条时间线。
 */
export interface NoteGroup {
  /** 分组键：'YYYY-MM-DD' */
  date: string
  /** 展示用标签：今天 / 昨天 / 09月25日 / 2025年12月31日 */
  label: string
  /** 该日期下的记事，按创建时刻倒序 */
  notes: Note[]
}
