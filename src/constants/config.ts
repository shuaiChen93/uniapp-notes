/**
 * 是否启用本地 Mock 服务。
 *
 * ⚠️ 这是本项目当前唯一需要关心的开关：
 * 现在没有后端，所有接口数据由 src/mock/ 生成，并用 uni storage 落盘持久化。
 * 接入真实后端时，把这里改成 false —— request.ts、api 层、store、页面
 * **全部无需改动**。因为 mock 只替换了「网络传输」这一层，
 * 上面的请求拦截、401 无感刷新、错误处理链路全部是真实逻辑。
 */
export const USE_MOCK = true

/**
 * Mock 请求的模拟延迟区间（毫秒）。
 *
 * 为什么要刻意加延迟：真实的网络请求不是 0ms 返回的。
 * 如果 mock 瞬时返回，开发期就看不到 loading 态、看不到骨架屏，
 * 等接上真后端才发现「loading 根本没写」——这类问题在阶段 3 才暴露成本很高。
 */
export const MOCK_DELAY_RANGE: readonly [number, number] = [180, 420]

/**
 * 接口基础路径。
 * 真实后端接入后改成实际域名，H5 端会命中 vite.config.ts 里的 /api 代理。
 */
export const API_BASE_URL = '/api'

/** 单次请求超时时间（毫秒） */
export const REQUEST_TIMEOUT = 15000

/**
 * accessToken 提前过期的安全余量（毫秒）。
 *
 * 判断「token 是否还有效」时不按过期时间卡点，而是提前这么久就算失效。
 * 原因：请求在网络上还要飞一会儿，如果卡着过期点放行，
 * 很可能出现「发出时有效、到达服务端时已过期」的 401，
 * 白白多一次刷新往返。这个余量是业界的常规做法。
 */
export const TOKEN_EXPIRY_SKEW = 30 * 1000
